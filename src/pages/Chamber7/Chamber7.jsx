function isAdjacent(a, b, size) {















  const ar = Math.floor(a / size);















  const ac = a % size;















  const br = Math.floor(b / size);















  const bc = b % size;































  return Math.abs(ar - br) + Math.abs(ac - bc) === 1;















}































